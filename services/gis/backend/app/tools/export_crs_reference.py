"""Export EPSG:5235 reference values for the web client's projection tests.

The web client measures distances in metres on the SLD99 / Sri Lanka Grid 1999 plane, the same way the
service does (ADR-02), so a radius the operator draws means the same thing as the ``distanceM`` the API
answers with. The client cannot call PROJ, so it carries its own implementation of the transformation -
and this tool exports what PROJ says the answers are, so a test can hold that implementation to it.

Usage (from ``backend/``)::

    python -m app.tools.export_crs_reference          # writes the fixture
    python -m app.tools.export_crs_reference --check  # fails if the fixture is out of date
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path
from typing import Final

import pyproj
from pyproj import Transformer

from app.core.config import REPOSITORY_ROOT
from app.spatial.crs import SLD99_GRID, WGS84

OUTPUT: Final = REPOSITORY_ROOT / "frontend" / "src" / "geo" / "sld99Reference.generated.ts"

# Longitudes and latitudes to project: the corners and centre of the service area, the projection's
# natural origin, and the fixture area around Habarana where the spatial tests work.
LONGITUDES: Final = (79.44, 80.0, 80.7717130833333, 80.75, 81.0, 81.5, 82.15)
LATITUDES: Final = (5.66, 6.5, 7.00047152777778, 8.03, 8.5, 9.5, 10.08)

# Pairs whose distance the client must reproduce: short (a geofence radius), medium (a district) and
# long (the length of the island), plus one pair that only differs in longitude.
PAIRS: Final = (
    ((80.7513, 8.0342), (80.7513, 8.0387)),
    ((80.7513, 8.0342), (80.7558, 8.0342)),
    ((80.7487, 8.0356), (80.8, 8.1)),
    ((79.86, 6.93), (81.23, 8.58)),
    ((79.44, 5.66), (82.15, 10.08)),
)


def _round(value: float) -> float:
    """Tenth of a millimetre: finer than anything the API reports, coarser than float noise."""
    return round(value, 4)


def reference() -> dict[str, object]:
    transformer = Transformer.from_crs(WGS84, SLD99_GRID, always_xy=True)
    points = []
    for lon in LONGITUDES:
        for lat in LATITUDES:
            easting, northing = transformer.transform(lon, lat)
            points.append({"lon": lon, "lat": lat, "easting": _round(easting), "northing": _round(northing)})
    distances = []
    for (from_lon, from_lat), (to_lon, to_lat) in PAIRS:
        start = transformer.transform(from_lon, from_lat)
        end = transformer.transform(to_lon, to_lat)
        distances.append(
            {
                "from": [from_lon, from_lat],
                "to": [to_lon, to_lat],
                "distanceM": _round(math.dist(start, end)),
            }
        )
    return {
        "epsg": SLD99_GRID,
        "projVersion": str(pyproj.proj_version_str),
        "pipeline": transformer.description,
        "points": points,
        "distances": distances,
    }


def _literal(value: object, indent: int = 0) -> str:
    pad = "  " * indent
    if isinstance(value, dict):
        entries = "".join(f"{pad}  {key}: {_literal(item, indent + 1)},\n" for key, item in value.items())
        return f"{{\n{entries}{pad}}}"
    if isinstance(value, (list, tuple)):
        if all(isinstance(item, (int, float)) and not isinstance(item, bool) for item in value):
            return "[" + ", ".join(_number(item) for item in value) + "]"
        entries = "".join(f"{pad}  {_literal(item, indent + 1)},\n" for item in value)
        return f"[\n{entries}{pad}]"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return _number(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def _number(value: float | int) -> str:
    return repr(int(value)) if isinstance(value, int) else repr(float(value))


def fixture() -> str:
    data = reference()
    return (
        "/**\n"
        " * EPSG:5235 (SLD99 / Sri Lanka Grid 1999) reference values, as PROJ computes them.\n"
        " *\n"
        " * Generated by `python -m app.tools.export_crs_reference` from the EPSG definition - do not edit.\n"
        " * `src/geo/sld99.ts` must reproduce these; `sld99.test.ts` is what holds it to them.\n"
        " */\n\n"
        f"export const SLD99_REFERENCE = {_literal(data)} as const;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the fixture is out of date")
    args = parser.parse_args()
    content = fixture()
    stale = not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content
    if args.check:
        if stale:
            print(f"out of date: {_relative(OUTPUT)}", file=sys.stderr)
        return 1 if stale else 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {_relative(OUTPUT)}")
    return 0


def _relative(path: Path) -> str:
    return str(path.relative_to(REPOSITORY_ROOT))


if __name__ == "__main__":
    sys.exit(main())
