"""The geo-context lookup uses spatial indexes on realistic table sizes.

The fixture worlds are tiny, so the planner would scan them sequentially whatever the query looks like.
This module adds a bulk reference release (20 000 settlements, 10 000 roads, 2 000 risk zones) and a bulk
tenant (20 000 devices, 10 000 geofences), analyses the tables and checks the plan of the real lookup
statement: every table access must be an index scan, and nearest searches must be index-ordered (KNN).

Tenant tables are protected by row-level security; their indexes are usable only when the ``&&``
operator is LEAKPROOF (``db/admin/postgis-leakproof.sql``). The container initialisation applies it.
"""

