async def _plan(world: SpatialWorld, tenant: TenantId, location: tuple[float, float]) -> dict[str, Any]:
    wkb = shapely.to_wkb(shapely.Point(*location), output_dimension=2)
    statement = text("EXPLAIN (FORMAT JSON) " + GEO_CONTEXT_LOOKUP_SQL).bindparams(*GEO_CONTEXT_LOOKUP_PARAMS)
    async with transaction(world.app_sessions, tenant) as session:
        document = await session.scalar(
            statement,
            {
                "wkb": wkb,
                "reference_point_wkb": wkb,
                "observed_at": datetime(2026, 9, 10, tzinfo=UTC),
                "release_code": BULK_RELEASE,
                "settlement_radius_m": 25_000.0,
                "road_radius_m": 10_000.0,
                "device_radius_m": 5_000.0,
                "device_limit": 5,
                "source_device_id": None,
            },
        )
    plans = document if isinstance(document, list) else json.loads(document)
    plan: dict[str, Any] = plans[0]["Plan"]
    return plan


def _nodes(plan: dict[str, Any]) -> Iterator[dict[str, Any]]:
    yield plan
    for child in plan.get("Plans", []):
        yield from _nodes(child)


async def _leakproof(world: SpatialWorld) -> bool:
    async with transaction(world.app_sessions) as session:
        value = await session.scalar(
            text(
                "SELECT p.proleakproof FROM pg_operator o JOIN pg_proc p ON p.oid = o.oprcode "
                "WHERE o.oprname = '&&' AND o.oprleft = 'public.geometry'::regtype "
                "AND o.oprright = 'public.geometry'::regtype"
            )
        )
    return bool(value)


def _spatial_sequential_scans(plan: dict[str, Any]) -> list[str]:
    """Sequential scans that evaluate a spatial predicate (small tables may be scanned otherwise)."""
    return [
        f"{node['Relation Name']}: {node.get('Filter')}"
        for node in _nodes(plan)
        if node["Node Type"] == "Seq Scan" and SPATIAL_PREDICATE.search(node.get("Filter", ""))
    ]


def _index_scans(plan: dict[str, Any], relation: str) -> list[dict[str, Any]]:
    return [
        node
        for node in _nodes(plan)
        if node.get("Relation Name") == relation and node["Node Type"] in {"Index Scan", "Index Only Scan"}
    ]


@pytest.mark.parametrize("tenant", [TENANT_A, BULK_TENANT])
async def test_reference_lookups_use_spatial_indexes(bulk_world: SpatialWorld, tenant: TenantId) -> None:
    plan = await _plan(bulk_world, tenant, HABARANA)
    assert _spatial_sequential_scans(plan) == []
    for relation in ("settlement", "road"):
        (nearest,) = [node for node in _index_scans(plan, relation) if "Order By" in node]
        assert nearest["Index Name"] == f"ix_{relation}_release_id_geom_metric_gist"
        assert "&&" in nearest["Index Cond"], "the search radius bounds the index scan"
    parts = _index_scans(plan, "area_part")
    assert len(parts) == 3, "admin areas, protected areas and risk zones"
    assert all("&&" in node["Index Cond"] for node in parts)


@pytest.mark.parametrize("tenant", [TENANT_A, BULK_TENANT])
async def test_tenant_lookups_use_spatial_indexes_under_row_level_security(
    bulk_world: SpatialWorld, tenant: TenantId
) -> None:
    if not await _leakproof(bulk_world):
        pytest.skip("run db/admin/postgis-leakproof.sql as a superuser to let RLS use spatial indexes")
    plan = await _plan(bulk_world, tenant, HABARANA)
    assert _spatial_sequential_scans(plan) == []
    fences = _index_scans(plan, "geofence")
    assert len(fences) == 2, "polygon geofences, and circles and corridors"
    assert all("&&" in node["Index Cond"] for node in fences)
    (devices,) = [node for node in _index_scans(plan, "device") if "Order By" in node]
    assert "&&" in devices["Index Cond"], devices
    assert _index_scans(plan, "device_field_of_view") != []


async def test_bulk_tenant_gets_correct_answers(bulk_world: SpatialWorld) -> None:
    """The index-driven statement returns what a brute-force computation returns."""
    location = HABARANA
    event = EventLocationIn.model_validate(
        {
            "eventId": "evt-bulk-1",
            "tenantId": BULK_TENANT.value,
            "observedAt": "2026-09-10T08:00:00Z",
            "eventType": "wildlife.elephant_detected",
            "sourceType": "sensor",
            "locationSource": "sensor",
            "location": {"type": "Point", "coordinates": list(location)},
        }
    )
    service = GeoContextService(bulk_world.app_sessions, bulk_world.service_area, GeoContextLimits())
    context = await service.enrich(event, release_code=BULK_RELEASE)
    async with transaction(bulk_world.app_sessions, BULK_TENANT) as session:
        expected = (
            await session.execute(
                text(
                    """
                    WITH p AS (SELECT public.ST_SetSRID(public.ST_MakePoint(:x, :y), 4326) AS p),
                    e AS (SELECT p.p, public.ST_Transform(p.p, 5235) AS g FROM p)
                    SELECT
                      (SELECT name FROM ref.settlement s, e, meta.ref_data_release r
                       WHERE r.id = s.release_id AND r.code = :code
                       ORDER BY public.ST_Distance(s.geom_metric, e.g), s.id LIMIT 1) AS settlement,
                      (SELECT array_agg(x.name ORDER BY x.distance, x.id)
                       FROM (SELECT d.name, d.id, public.ST_Distance(d.geom_metric, e.g) AS distance
                             FROM ops.device d, e
                             WHERE d.status = 'active' AND public.ST_Distance(d.geom_metric, e.g) <= 5000
                             ORDER BY 3, 2 LIMIT 5) AS x) AS devices,
                      (SELECT count(*) FROM ops.geofence f, e
                       WHERE (f.geofence_kind = 'polygon' AND public.ST_Intersects(f.geom, e.p))
                          OR (f.geofence_kind = 'circle'
                              AND public.ST_Distance(f.definition_geom_metric, e.g) <= f.radius_m)) AS fences,
                      (SELECT count(*) FROM ref.risk_zone z, e, meta.ref_data_release r
                       WHERE r.id = z.release_id AND r.code = :code
                         AND public.ST_Intersects(z.geom, e.p)) AS zones
                    """
                ),
                {"x": location[0], "y": location[1], "code": BULK_RELEASE},
            )
        ).one()
    assert context.nearest_settlement is not None
    assert context.nearest_settlement.name == expected.settlement
    assert [device.name for device in context.nearest_devices] == list(expected.devices)
    assert len(context.geofence_hits) == expected.fences
    assert len(context.inside_zones) == expected.zones
